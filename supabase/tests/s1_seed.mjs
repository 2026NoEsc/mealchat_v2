// Deterministic local-only DATA seed. The production template remains held outside migrations.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { templatePath } from './s1_m7_local.mjs';
const here=dirname(fileURLToPath(import.meta.url));
const start='-- BEGIN S1 LOCAL-DEV SEED';
const end='-- END S1 LOCAL-DEV SEED';
// The old migration creates one unlinked legacy bundle even in a fresh local DB.
// Allow it only in its original shape AND a user/consent-free database.
const guard = ` if exists(select 1 from public.consent_documents d where (d.kind,d.version) not in
  (('service','service-local-dev-v2'),('privacy','privacy-local-dev-v2'),('health','health-local-dev-v1'),('marketing','marketing-local-dev-v1')))
 or exists(select 1 from public.terms_versions t where t.version<>'mealchat-local-dev-r2' and not
  (t.version='2026-08-17' and t.service_document_id is null and t.privacy_document_id is null and t.published_at is null and t.change_summary=''))
 or exists(select 1 from auth.users) or exists(select 1 from public.profiles) or exists(select 1 from public.profile_consents) then
  raise exception 'S1_LOCAL_SEED_NONLOCAL_STATE' using errcode='55000';
 end if;`;

export function localSeedBlock() {
 const documents={};
 for(const kind of ['service','privacy','health','marketing']) {
  const edition=['service','privacy'].includes(kind)?2:1;
  const data={id:kind==='service'?'terms':kind,title:'LOCAL DEV '+kind+' - 운영 약관 아님',effectiveDate:'2020년 1월 1일',edition,sections:[{id:'local-dev',title:'로컬 개발용 테스트 문서',paragraphs:['이 문서는 로컬 S1 가입·재동의 화면 검증용이에요. 실제 약관이나 운영 동의로 사용하지 마세요.']}]};
  const canonical_content=JSON.stringify(data)+'\n';
  documents[kind]={version:kind+'-local-dev-v'+edition,edition,effective_from:'2019-12-31T15:00:00Z',content_hash:createHash('sha256').update(canonical_content).digest('hex'),canonical_content};
 }
 const source=readFileSync(templatePath,'utf8');
 let sql=source.replace(/privacy_release constant jsonb := \$s1_privacy\$[\s\S]*?\$s1_privacy\$::jsonb;/,()=> 'privacy_release constant jsonb := $s1_privacy$\n'+JSON.stringify(documents.privacy,null,2)+'\n$s1_privacy$::jsonb;');
 const fixed=Object.fromEntries(['service','health','marketing'].map(k=>[k,documents[k]]));
 sql=sql.replace(/documents constant jsonb := \$s1_documents\$[\s\S]*?\$s1_documents\$::jsonb;/,()=> 'documents constant jsonb := $s1_documents$\n'+JSON.stringify(fixed,null,2)+'\n$s1_documents$::jsonb;');
 sql=sql.replace(/bundle_version := 'mealchat-'[^;]+;/,"bundle_version := 'mealchat-local-dev-r2';");
 sql=sql.slice(sql.indexOf('begin;'));
 // Preflight is first; repeat under the publication lock to reject a concurrent publisher.
 sql=sql.replace('begin;','begin;\ndo $s1_local_seed_guard$ begin\n'+guard+'\nend; $s1_local_seed_guard$;');
 const publicationLock=' lock table public.consent_documents,public.terms_versions in share row exclusive mode;';
 if(!sql.includes(publicationLock))throw new Error('Seed publication lock missing');
 sql=sql.replace(publicationLock,()=>publicationLock+'\n'+guard);
 return start+'\n-- Generated by node supabase/tests/s1_seed.mjs. All document versions are local-dev.\n-- Local reset/start only. Never copy into migrations or push with --include-seed.\n'+sql.trim()+'\n'+end+'\n';
}
export function seedIsCurrent(text) { const a=text.indexOf(start),b=text.indexOf(end);return a>=0&&b>=a&&text.slice(a,b+end.length)+'\n'===localSeedBlock(); }
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
 const target=resolve(here,'../seed.sql');
 const existing=existsSync(target)?readFileSync(target,'utf8'):'';
 if(process.argv.includes('--check')) { if(!seedIsCurrent(existing))throw new Error('Local S1 seed is stale: run node supabase/tests/s1_seed.mjs'); console.log('Local-dev seed matches the release template logic.'); }
 else {
  const a=existing.indexOf(start),b=existing.indexOf(end);
  if((a<0)!==(b<0))throw new Error('Incomplete local seed markers');
  const output=a<0?existing+(existing&&!existing.endsWith('\n')?'\n':'')+localSeedBlock():existing.slice(0,a)+localSeedBlock()+existing.slice(b+end.length).replace(/^\r?\n/,'');
  writeFileSync(target,output,'utf8');
 }
}
