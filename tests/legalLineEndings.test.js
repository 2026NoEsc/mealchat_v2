const { execFileSync } = require('node:child_process');
const { copyFileSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } = require('node:fs');
const { tmpdir } = require('node:os');
const { join, resolve, dirname } = require('node:path');
const published = require('../src/legal/documents.generated.json');

function withCrlfCheckout(check) {
  const parent = resolve(tmpdir());
  const fixture = mkdtempSync(join(parent, 'mealchat-legal-eol-'));
  try {
    mkdirSync(join(fixture, 'scripts'));
    mkdirSync(join(fixture, 'src/legal'), { recursive: true });
    copyFileSync('scripts/generate-legal-hashes.mjs', join(fixture, 'scripts/generate-legal-hashes.mjs'));
    for (const name of readdirSync('src/legal').filter(name => /\.(ts|json)$/.test(name))) {
      const source = readFileSync(join('src/legal', name), 'utf8').replace(/\r\n?/g, '\n');
      writeFileSync(join(fixture, 'src/legal', name), source.replace(/\n/g, '\r\n'));
    }
    const run = () => execFileSync(process.execPath, ['scripts/generate-legal-hashes.mjs', '--check'], {
      cwd: fixture, encoding: 'utf8', stdio: 'pipe', env: { ...process.env, NODE_PATH: resolve('node_modules') },
    });
    check(fixture, run);
  } finally {
    // Delete only this test-created directory, never a shared dependency directory.
    if (dirname(resolve(fixture)) !== parent || !fixture.startsWith(join(parent, 'mealchat-legal-eol-'))) throw new Error('Unexpected fixture path');
    rmSync(fixture, { recursive: true, force: true });
  }
}
it('checks a CRLF checkout without changing any published legal hash or generated bytes', () => {
  withCrlfCheckout((fixture, run) => {
    const target = join(fixture, 'src/legal/documents.generated.json');
    const before = readFileSync(target);
    expect(before.toString('utf8')).toContain('\r\n');
    const output = run();
    for (const document of Object.values(published)) expect(output).toContain(document.version + ' ' + document.content_hash);
    expect(readFileSync(target)).toEqual(before);
  });
});
it('still rejects a substantive generated-document change in a CRLF checkout', () => {
  withCrlfCheckout((fixture, run) => {
    const target = join(fixture, 'src/legal/documents.generated.json');
    const changed = JSON.parse(readFileSync(target, 'utf8'));
    changed.service.content_hash = '0'.repeat(64);
    writeFileSync(target, (JSON.stringify(changed, null, 2) + '\n').replace(/\n/g, '\r\n'));
    expect(run).toThrow(/Legal documents changed/);
  });
});
it('pins legal source and generated artifacts to LF for new Windows checkouts', () => {
  const attributes = readFileSync('.gitattributes', 'utf8');
  expect(attributes).toMatch(/^src\/legal\/\*\.ts text eol=lf$/m);
  expect(attributes).toMatch(/^src\/legal\/\*\.json text eol=lf$/m);
});
